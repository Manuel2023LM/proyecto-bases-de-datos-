-- Actualiza cuentas de aplicacion y repara texto guardado con Windows-1252.
BEGIN;
SET LOCAL client_encoding TO 'UTF8';
SET LOCAL search_path TO censo_terremoto,public;

CREATE TABLE IF NOT EXISTS usuario_app
(
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('administrador','encargado','persona')),
    persona_id_persona BIGINT UNIQUE REFERENCES persona(id_persona),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuario_app_persona_ck CHECK (rol <> 'persona' OR persona_id_persona IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS admin_bootstrap_state
(
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    admin_id BIGINT NOT NULL UNIQUE REFERENCES usuario_app (id_usuario),
    used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
DECLARE
    item RECORD;
    repair_pass INTEGER;
BEGIN
    FOR repair_pass IN 1..3 LOOP
        FOR item IN
            SELECT table_name, column_name
            FROM information_schema.columns
            WHERE table_schema='censo_terremoto'
              AND data_type IN ('character varying','character','text')
              AND table_name IN (
                  SELECT table_name
                  FROM information_schema.tables
                  WHERE table_schema='censo_terremoto'
                    AND table_type='BASE TABLE'
              )
        LOOP
            EXECUTE format(
                'UPDATE censo_terremoto.%I SET %I=convert_from(convert_to(%I,%L),%L) '
                'WHERE position(%L in %I)>0 OR position(%L in %I)>0',
                item.table_name, item.column_name, item.column_name, 'WIN1252', 'UTF8',
                chr(195), item.column_name, chr(194), item.column_name
            );
        END LOOP;
    END LOOP;
END $$;

COMMIT;
